const TABLES = { en: EN, he: HE };
let current = 'en';
const listeners = new Set();

export const i18n = {
  get lang() { return current; },
  get rtl() { return current === 'he'; },
  set(lang) {
    if (!TABLES[lang]) lang = 'en';
    current = lang;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'he' ? 'rtl' : 'ltr';
    try { localStorage.setItem('vantage.lang', lang); } catch (e) { /* ignore */ }
    for (const l of listeners) l(lang);
  },
  t(key, vars) {
    let s = TABLES[current][key] ?? EN[key] ?? key;
    if (vars) for (const k in vars) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    return s;
  },
  onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); },
  detect() {
    let saved = null;
    try { saved = localStorage.getItem('vantage.lang'); } catch (e) { /* ignore */ }
    if (saved && TABLES[saved]) return saved;
    const nav = (navigator.language || 'en').toLowerCase();
    return nav.startsWith('he') || nav.startsWith('iw') ? 'he' : 'en';
  },
};

export const t = (k, v) => i18n.t(k, v);
