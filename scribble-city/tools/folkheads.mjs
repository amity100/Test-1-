// Bakes the heads of the city's people (v5, ROADMAP 13.6) from the MakeHuman base mesh and its
// targets - both released as CC0 by the MakeHuman team (makehumancommunity.org). The head is cut
// from the body, put in our head's frame (metres; x right, y up, z ahead; its eyes where our faces'
// drawings have them, render/folkink.js), and each target's moves of it kept for the head alone.
//
// usage: node tools/folkheads.mjs <dir>
//   <dir>/base.obj        makehuman/data/3dobjs/base.obj of github.com/makehumancommunity/makehuman
//   <dir>/targets/*.target makehuman/data/targets/<group>/<name>.target, saved as <group>_<name>.target
// writes v5/js/render/folkheads.js
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node tools/folkheads.mjs <dir with base.obj and targets/>');
  process.exit(1);
}
// (decimetres to metres, a little larger: the eyes 64 mm apart, as our drawings have them)
const S = 0.104;
const EYE_Y = 7.2841;
const EYE_Z = 1.2454;
const toOurs = (x, y, z) => [S * x, S * (y - EYE_Y) + 0.0185, S * (z - EYE_Z) + 0.072];
// (the head and its neck's top: everything above this, in the base mesh's decimetres)
const CUT = 6.2;

// ------------------------------------------------------------------ the base mesh
const V = [];
const faces = [];
const groups = new Map();
let cur = null;
for (const line of fs.readFileSync(path.join(dir, 'base.obj'), 'utf8').split('\n')) {
  if (line.startsWith('v ')) V.push(line.split(/\s+/).slice(1, 4).map(Number));
  else if (line.startsWith('g ')) {
    cur = line.split(/\s+/)[1];
    if (!groups.has(cur)) groups.set(cur, []);
  } else if (line.startsWith('f ')) {
    groups.get(cur).push(faces.length);
    faces.push(line.trim().split(/\s+/).slice(1).map((p) => parseInt(p, 10) - 1));
  }
}
const head = groups.get('body').map((i) => faces[i]).filter((f) => f.every((v) => V[v][1] > CUT));
const used = [...new Set(head.flat())].sort((a, b) => a - b);
const local = new Map(used.map((v, i) => [v, i]));
const pos = new Int16Array(used.length * 3);
const Q = 1e-5;
used.forEach((v, i) => {
  const p = toOurs(...V[v]);
  for (let k = 0; k < 3; k++) pos[i * 3 + k] = Math.round(p[k] / Q);
});
const idx = [];
for (const f of head) {
  const a = f.map((v) => local.get(v));
  idx.push(a[0], a[1], a[2]);
  if (a.length === 4) idx.push(a[0], a[2], a[3]);
}
// (landmarks: the lobe of each ear - its lowest point - and its top, behind the jaw, by the temple)
const ours = used.map((v) => toOurs(...V[v]));
const onEar = (p, sd) => sd * p[0] > 0.066 && p[2] < 0.004 && p[2] > -0.048 && p[1] > -0.045 && p[1] < 0.045;
const pick = (sd, better) => {
  let best = -1;
  ours.forEach((p, i) => {
    if (onEar(p, sd) && (best < 0 || better(p, ours[best]))) best = i;
  });
  return best;
};
const lobe = [1, -1].map((sd) => pick(sd, (p, q) => p[1] < q[1]));
const earTop = [1, -1].map((sd) => pick(sd, (p, q) => p[1] > q[1]));

// ------------------------------------------------------------------ the targets
const morphs = {};
const tdir = path.join(dir, 'targets');
for (const file of fs.readdirSync(tdir).filter((f) => f.endsWith('.target')).sort()) {
  const name = file.replace(/\.target$/, '').replace(/^[a-z]+_/, '');
  const ix = [];
  const d = [];
  for (const line of fs.readFileSync(path.join(tdir, file), 'utf8').split('\n')) {
    if (!/^\d/.test(line)) continue;
    const [v, x, y, z] = line.trim().split(/\s+/).map(Number);
    if (!local.has(v)) continue;
    ix.push(local.get(v));
    d.push(x * S, y * S, z * S);
  }
  if (!ix.length) continue;
  // (each move to a hundredth of a millimetre, in a byte when it fits: the target's own scale)
  const m = Math.max(...d.map(Math.abs));
  const scale = m / 127;
  const q = Int8Array.from(d.map((x) => Math.round(x / scale)));
  morphs[name] = { s: +scale.toExponential(4), i: b64(Uint16Array.from(ix)), d: b64(q) };
}

function b64(a) {
  return Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString('base64');
}

const out = `// GENERATED by tools/folkheads.mjs - do not edit by hand.
// (v5, ROADMAP 13.6) The heads of the city's people: the MakeHuman base mesh's head and the moves of
// its targets (CC0, the MakeHuman team: makehumancommunity.org), in our head's frame - metres, x
// right, y up, z ahead, the eyes at (+-0.032, 0.0185). pos: Int16 (x ${Q} m); idx: Uint16
// triangles; lobe, earTop: vertices [right, left]; MORPHS[name]: { s: scale, i: Uint16 vertices,
// d: Int8 moves (x s) } - all base64.
export const HEAD = ${JSON.stringify({ n: used.length, q: Q, pos: b64(pos), idx: b64(Uint16Array.from(idx)), lobe, earTop })};
export const MORPHS = ${JSON.stringify(morphs)};
`;
const file = path.join(path.dirname(new URL(import.meta.url).pathname), '../v5/js/render/folkheads.js');
fs.writeFileSync(file, out);
console.log('head', used.length, 'vertices', idx.length / 3, 'triangles,', Object.keys(morphs).length, 'targets,', (out.length / 1024).toFixed(0), 'KB ->', file);
