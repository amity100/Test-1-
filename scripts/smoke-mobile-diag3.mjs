import { chromium, devices } from 'playwright-core';
const url = process.argv[2] || 'http://localhost:5173/?debug=low,nofoliage';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--no-sandbox', '--use-gl=angle'] });
const phone = devices['Pixel 7'] || devices['Pixel 5'];
const ctx = await browser.newContext({ ...phone, viewport: { width: 860, height: 400 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const cdp = await ctx.newCDPSession(page);
page.on('pageerror', (e) => console.log('[pageerror]', e.message)); page.on('console', (m) => { if (m.text().startsWith('[touch]')) console.log(m.text()); });
const touch = async (type, points) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: points.map((p, i) => ({ x: p.x, y: p.y, id: i })) });
await page.goto(url, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__fk && (window.__fk.ready || window.__fk.error), { timeout: 240000 });
await page.evaluate(() => { window.__touchDebug = true; window.__fk.game().debugQuickMatch(2, 'easy', 60); });
await page.waitForTimeout(1500);
await page.evaluate(() => {
  const g = window.__fk.game(); const inp = g.app.input; const b = g.build;
  window.__log = [];
  const origEnd = inp.endFrame.bind(inp);
  inp.endFrame = () => { if (inp.virtual.tapped || inp.virtual.primary) window.__log.push(`endFrame tapped=${inp.virtual.tapped} primary=${inp.virtual.primary}`); origEnd(); };
  const origUpd = b.update.bind(b);
  b.update = (dt) => { if (inp.virtual.tapped || inp.virtual.primary) window.__log.push(`build.update sees tapped=${inp.virtual.tapped} primary=${inp.virtual.primary} uiHover=${b.uiHover} active=${b.active} paused=${g.paused} mode=${g.mode}`); origUpd(dt); };
  const origGU = g.update.bind(g);
  g.update = (dt) => { if (inp.virtual.tapped) window.__log.push(`game.update tapped mode=${g.mode} paused=${g.paused}`); return origGU(dt); };
  const zones = document.querySelectorAll('.touch-ui .tz');
  zones.forEach((z) => z.addEventListener('pointerup', () => window.__log.push(`pointerup zone tapped=${inp.virtual.tapped}`), true));
});
await touch('touchStart', [{ x: 430, y: 224 }]);
await page.waitForTimeout(60);
await touch('touchEnd', []);
await page.waitForTimeout(1200);
console.log(JSON.stringify(await page.evaluate(() => ({ log: window.__log, used: window.__fk.game().build.state.used }))));
await browser.close();
